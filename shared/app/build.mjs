/**
 * The native copy and colour generator of the Trakly apps (docs/specs/phase10-apps-and-stores.md D17, §B13, §D11, §J4).
 * One source each, written by hand: `shared/app/copy.fa.json` (every native Persian string) and `shared/app/tokens.json`
 * (the colours of docs/DESIGN.md §3, the night colour of §7). Plain Node, no dependency.
 *
 *   node shared/app/build.mjs                    validates both sources and rewrites the outputs of every platform that
 *                                                adopted the generator (see below)
 *   node shared/app/build.mjs --platform=ios     also writes (adopts) that platform's outputs; `android`, `ios` or both
 *                                                (`--platform=android,ios`)
 *   node shared/app/build.mjs --check            validates both sources; every output of an adopted platform must equal
 *                                                a fresh generation (exit code 1 otherwise)
 *
 * Outputs (paths from the repo root):
 * - Android: `android/app/src/main/res/values/strings.xml` (+ `app_name`, `asset_statements`, `share_label`),
 *   `values/colors.xml`, `values-night/colors.xml`;
 * - iOS: `ios/Trakly/Resources/fa.lproj/Localizable.strings`, `ios/Trakly/Resources/fa.lproj/InfoPlist.strings` (the
 *   `plist_*` keys under their Info.plist names), `ios/TraklyShare/fa.lproj/Localizable.strings` (the share extension's
 *   keys), `ios/Trakly/Resources/Assets.xcassets/Colors/<Name>.colorset/Contents.json` (incl. `Night` and
 *   `LaunchBackground` = the night colour).
 *
 * A platform is **adopted** once its main strings file carries the generator header: Android when W3 replaces the
 * hand-written phase 9 `strings.xml` (C7: its launcher, token and drop strings are not carried over, so the phase 9 app
 * would not compile against the generated file), iOS when W5 starts `ios/`. Until then `--check` proves the sources and a
 * generation in memory, and names the platform as pending. Android's `checkSharedCopy` and both `source.check.mjs`
 * require the header from then on.
 *
 * The rules (D17, §B13): keys `^[a-z][a-z0-9_]*$`; a value is a string or `{text, platforms}`; placeholders `%s` and `%d`
 * only (iOS gets `%@` and `%d`; two or more become positional); refused anywhere: U+200C, the diacritic marks
 * U+064B–U+065F and U+0670, U+06C0, U+0623, U+0625, U+0624, «·», a bidi control other than a closed isolate, a tab or a
 * line break, two spaces, and the words of BANNED; `Android` and `اندروید` in a key shipped to iOS; `iPhone` and `آیفون`
 * in a key shipped to Android. **Bidi:** a leading Latin run of a right-to-left value is wrapped in LRI … PDI (U+2066 …
 * U+2069) and every placeholder in FSI … PDI (U+2068 … U+2069), written as escapes (`\u2066` in strings.xml, `\U2066`
 * in `.strings`).
 *
 * Every generated text file starts with a header naming its source and the SHA-256 of that source with LF line endings
 * (`sha256=<64 hex>`, HEADER_PATTERN), which Android's `checkSharedCopy` compares without running Node.
 *
 * Test seam: `--root <dir>` writes and checks the outputs under another root (the sources stay these).
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO = path.resolve(HERE, '..', '..');
export const COPY_FILE = path.join(HERE, 'copy.fa.json');
export const TOKENS_FILE = path.join(HERE, 'tokens.json');

/** The marker every generated file carries. */
export const MARKER = 'GENERATED by shared/app/build.mjs';
/** `sha256=<hex>` of the source (LF line endings) in a generated header. */
export const HEADER_PATTERN = /sha256=([0-9a-f]{64})/;

export const PLATFORMS = ['android', 'ios'];

/** The origin of the Android app's `asset_statements` (the release origin, §D3). */
export const ORIGIN = 'https://erp.trakly.info';

/** iOS Info.plist keys of InfoPlist.strings, from their copy keys (§J4). */
export const INFO_PLIST_KEYS = {
    NSCameraUsageDescription: 'plist_camera_usage',
    NSFaceIDUsageDescription: 'plist_face_id_usage',
    NSPhotoLibraryAddUsageDescription: 'plist_photo_add_usage',
};

/** The keys the iOS share extension `TraklyShare` shows (§E8). */
export const SHARE_EXTENSION_KEYS = ['share_title', 'share_saved', 'share_no_link'];

/** Android strings that are not translatable (the brand, the App Links statement). */
const NOT_TRANSLATABLE = new Set(['app_name', 'asset_statements']);

/** The output files, relative to the repo root. */
export const OUTPUTS = {
    android: {
        strings: 'android/app/src/main/res/values/strings.xml',
        colors: 'android/app/src/main/res/values/colors.xml',
        nightColors: 'android/app/src/main/res/values-night/colors.xml',
    },
    ios: {
        strings: 'ios/Trakly/Resources/fa.lproj/Localizable.strings',
        infoPlist: 'ios/Trakly/Resources/fa.lproj/InfoPlist.strings',
        shareStrings: 'ios/TraklyShare/fa.lproj/Localizable.strings',
        colors: 'ios/Trakly/Resources/Assets.xcassets/Colors',
    },
};

/** The writing rule (App\Support\PersianWriting) plus the middle dot, written with escapes. */
const FORBIDDEN_CHARS = /[\u200C\u064B-\u065F\u0670\u06C0\u0623\u0625\u0624\u00B7]/u;
/** Bidi controls other than the isolates, and the other invisible marks. */
const FORBIDDEN_CONTROLS = /[\u061C\u200B\u200D-\u200F\u202A-\u202E\uFEFF]/u;
const ISOLATE_OPEN = /[\u2066\u2067\u2068]/u;
const PDI = '\u2069';
const LRI = '\u2066';
const FSI = '\u2068';

/** No store, no circumvention tool and no circumvention advice in native copy (D17, §B13; Bazaar, Myket, Apple). */
export const BANNED = ['فیلترشکن', 'VPN', 'بازار', 'مایکت', 'Google Play', 'گوگل پلی', 'App Store', 'اپ استور', 'برنامه اتصال', 'تونل', 'فقط برای برنامه های انتخاب شده'];
/** Platform names a build must not ship (Apple 2.3.10; one copy serves every store build of a platform). */
export const BANNED_FOR = { ios: ['Android', 'اندروید'], android: ['iPhone', 'آیفون'] };

const KEY = /^[a-z][a-z0-9_]*$/;
const PLACEHOLDER = /%[sd]/g;
const ARABIC = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFE]/u;
const LEADING_LATIN = /^[A-Za-z][A-Za-z0-9 ._:/+&'-]*/;
const COLOR_HEX = /^#[0-9A-Fa-f]{6}$/;
const COLOR_RGBA = /^rgba\((\d{1,3}),(\d{1,3}),(\d{1,3}),(0|1|0?\.\d+|1\.0+)\)$/;

/** A source file's text with LF line endings (git may check it out with CRLF on Windows). */
export function sourceText(file) {
    return readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

export function sha256(text) {
    return createHash('sha256').update(text, 'utf8').digest('hex');
}

// ---- validation ------------------------------------------------------------------------------------------------------

/**
 * The copy as `[{key, text, platforms}]` in source order, or throws with every problem.
 * @param {unknown} copy
 */
export function readCopy(copy) {
    const problems = [];
    const entries = [];

    if (copy === null || typeof copy !== 'object' || Array.isArray(copy)) {
        throw new Error('copy.fa.json must be an object of key → text');
    }

    for (const [key, value] of Object.entries(copy)) {
        let text = value;
        let platforms = [...PLATFORMS];

        if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
            const extra = Object.keys(value).filter((name) => name !== 'text' && name !== 'platforms');

            if (extra.length > 0) {
                problems.push(`${key}: unknown fields ${extra.join(', ')}`);
            }

            text = value.text;
            platforms = value.platforms;

            if (!Array.isArray(platforms) || platforms.length === 0 || platforms.some((p) => !PLATFORMS.includes(p)) || new Set(platforms).size !== platforms.length) {
                problems.push(`${key}: platforms must be a non-empty subset of ${PLATFORMS.join(', ')}`);
                platforms = [...PLATFORMS];
            }
        }

        if (!KEY.test(key)) {
            problems.push(`${key}: keys are ^[a-z][a-z0-9_]*$`);
        }

        if (typeof text !== 'string' || text.trim() === '') {
            problems.push(`${key}: the text must be a non-empty string`);
            continue;
        }

        problems.push(...textProblems(key, text, platforms));
        entries.push({ key, text, platforms });
    }

    for (const [plist, key] of Object.entries(INFO_PLIST_KEYS)) {
        const entry = entries.find((item) => item.key === key);

        if (!entry || !entry.platforms.includes('ios')) {
            problems.push(`${key}: missing (iOS ${plist})`);
        }
    }

    for (const key of SHARE_EXTENSION_KEYS) {
        if (!entries.some((item) => item.key === key && item.platforms.includes('ios'))) {
            problems.push(`${key}: missing (the iOS share extension)`);
        }
    }

    if (!entries.some((item) => item.key === 'app_name')) {
        problems.push('app_name: missing');
    }

    if (problems.length > 0) {
        throw new Error(`shared/app/copy.fa.json:\n  ${problems.join('\n  ')}`);
    }

    return entries;
}

/** Every rule a text breaks (D17, §B13). */
export function textProblems(key, text, platforms) {
    const problems = [];
    const lower = text.toLowerCase();

    if (FORBIDDEN_CHARS.test(text)) {
        problems.push(`${key}: a half-space, a diacritic mark, a hamza form or «·» (the writing rule)`);
    }

    if (FORBIDDEN_CONTROLS.test(text) || /[\t\n\r]/.test(text)) {
        problems.push(`${key}: an invisible mark, a bidi control other than an isolate, a tab or a line break`);
    }

    if (/ {2}/.test(text) || text !== text.replace(/^ +/, '')) {
        problems.push(`${key}: two spaces or a leading space`);
    }

    if (!isolatesBalanced(text)) {
        problems.push(`${key}: an isolate (U+2066–U+2068) without its U+2069, or the reverse`);
    }

    const bare = text.replace(PLACEHOLDER, '');

    if (bare.includes('%')) {
        problems.push(`${key}: only %s and %d may follow a percent sign`);
    }

    for (const word of BANNED) {
        if (lower.includes(word.toLowerCase())) {
            problems.push(`${key}: «${word}» (no store, no circumvention tool or advice in native copy)`);
        }
    }

    for (const platform of platforms) {
        for (const word of BANNED_FOR[platform]) {
            if (lower.includes(word.toLowerCase())) {
                problems.push(`${key}: «${word}» in a text shipped to ${platform}`);
            }
        }
    }

    return problems;
}

function isolatesBalanced(text) {
    let depth = 0;

    for (const char of text) {
        if (ISOLATE_OPEN.test(char)) {
            depth++;
        } else if (char === PDI) {
            depth--;

            if (depth < 0) {
                return false;
            }
        }
    }

    return depth === 0;
}

/**
 * The colours as `{colors: [{name, light, dark}], night}` (`#RRGGBBAA`-free ARGB integers), or throws.
 * @param {unknown} tokens
 */
export function readTokens(tokens) {
    const problems = [];

    if (tokens === null || typeof tokens !== 'object' || Array.isArray(tokens)) {
        throw new Error('tokens.json must be an object');
    }

    const colors = [];
    const pascal = new Set();

    for (const [name, value] of Object.entries(tokens.colors ?? {})) {
        if (!KEY.test(name)) {
            problems.push(`colors.${name}: names are ^[a-z][a-z0-9_]*$`);
        }

        if (pascal.has(pascalCase(name))) {
            problems.push(`colors.${name}: clashes with another name as an asset name`);
        }

        pascal.add(pascalCase(name));
        const light = parseColor(value?.light, false);
        const dark = parseColor(value?.dark, true);

        if (light === null) {
            problems.push(`colors.${name}.light: #RRGGBB`);
        }

        if (dark === null) {
            problems.push(`colors.${name}.dark: #RRGGBB or rgba(r,g,b,a)`);
        }

        colors.push({ name, light, dark });
    }

    if (colors.length === 0) {
        problems.push('colors: at least one colour');
    }

    if (['night', 'launch_background'].some((name) => colors.some((color) => color.name === name))) {
        problems.push('colors: `night` and `launch_background` are written from the top-level `night`');
    }

    const night = parseColor(tokens.night, false);

    if (night === null) {
        problems.push('night: #RRGGBB');
    }

    if (!Number.isInteger(tokens.radius?.control) || !Number.isInteger(tokens.radius?.card) || !Number.isInteger(tokens.button?.height)) {
        problems.push('radius.control, radius.card and button.height: integers (dp / pt)');
    }

    if (problems.length > 0) {
        throw new Error(`shared/app/tokens.json:\n  ${problems.join('\n  ')}`);
    }

    return { colors, night };
}

/** `{r, g, b, a}` (a in 0..1) of `#RRGGBB` or, when allowed, `rgba(r,g,b,a)`; null when malformed. */
function parseColor(value, allowAlpha) {
    if (typeof value !== 'string') {
        return null;
    }

    if (COLOR_HEX.test(value)) {
        return { r: parseInt(value.slice(1, 3), 16), g: parseInt(value.slice(3, 5), 16), b: parseInt(value.slice(5, 7), 16), a: 1 };
    }

    const match = allowAlpha ? COLOR_RGBA.exec(value) : null;

    if (!match) {
        return null;
    }

    const [r, g, b, a] = [Number(match[1]), Number(match[2]), Number(match[3]), Number(match[4])];

    return r <= 255 && g <= 255 && b <= 255 && a >= 0 && a <= 1 ? { r, g, b, a } : null;
}

export function pascalCase(name) {
    return name
        .split('_')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join('');
}

// ---- bidi ----------------------------------------------------------------------------------------------------------

/**
 * A text as shipped: a leading Latin run of a right-to-left text wrapped in LRI … PDI, every placeholder in FSI … PDI
 * (numbered `%1$s`, `%2$s` … when there are two or more), `%s` written as `placeholder` (`%@` on iOS).
 */
export function shippedText(text, { string = '%s' } = {}) {
    let result = text;

    if (ARABIC.test(result) && !ISOLATE_OPEN.test(result.charAt(0))) {
        const run = LEADING_LATIN.exec(result)?.[0].replace(/[ ._:/+&'-]+$/, '');

        if (run) {
            result = LRI + run + PDI + result.slice(run.length);
        }
    }

    const count = (text.match(PLACEHOLDER) ?? []).length;
    let index = 0;

    return result.replace(PLACEHOLDER, (placeholder) => {
        index++;
        const type = placeholder === '%s' ? string.slice(1) : 'd';

        return FSI + (count > 1 ? `%${index}$${type}` : `%${type}`) + PDI;
    });
}

/** The bidi rule on a shipped text: a right-to-left text never starts with a bare Latin letter; placeholders isolated. */
export function bidiProblems(key, shipped) {
    const problems = [];

    if (ARABIC.test(shipped) && /^[A-Za-z]/.test(shipped)) {
        problems.push(`${key}: an unwrapped leading Latin run`);
    }

    if (/(?<!\u2068)%(?:\d+\$)?[sd@]/.test(shipped) || /%(?:\d+\$)?[sd@](?!\u2069)/.test(shipped)) {
        problems.push(`${key}: a placeholder outside FSI … PDI`);
    }

    return problems;
}

// ---- writers -------------------------------------------------------------------------------------------------------

function androidEscape(text) {
    let out = text
        .replace(/\\/g, '\\\\')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/'/g, "\\'")
        .replace(/"/g, '\\"')
        .replace(/[\u2066-\u2069]/g, (char) => '\\u' + char.charCodeAt(0).toString(16));

    if (out.startsWith('@') || out.startsWith('?')) {
        out = '\\' + out;
    }

    // Android collapses and trims plain spaces at the ends of a resource; an escaped one stays.
    return out.replace(/^ /, '\\u0020').replace(/ $/, '\\u0020');
}

function stringsEscape(text) {
    return text
        .replace(/\\/g, '\\\\')
        .replace(/"/g, '\\"')
        .replace(/[\u2066-\u2069]/g, (char) => '\\U' + char.charCodeAt(0).toString(16));
}

function xmlHeader(source, hash) {
    return `<!-- ${MARKER} from ${source} (sha256=${hash}, the source with LF line endings). Do not edit: change the source
     and run node shared/app/build.mjs (docs/specs/phase10-apps-and-stores.md D17, §B13). -->`;
}

function stringsHeader(source, hash) {
    return `/* ${MARKER} from ${source} (sha256=${hash}, the source with LF line endings). Do not edit: change the source and run node shared/app/build.mjs (docs/specs/phase10-apps-and-stores.md D17, §B13). */`;
}

function hex2(value) {
    return value.toString(16).toUpperCase().padStart(2, '0');
}

/** `#RRGGBB`, or `#AARRGGBB` with alpha (Android). */
function androidColor({ r, g, b, a }) {
    const rgb = hex2(r) + hex2(g) + hex2(b);

    return a === 1 ? `#${rgb}` : `#${hex2(Math.round(a * 255))}${rgb}`;
}

function colorsetColor({ r, g, b, a }) {
    return { 'color-space': 'srgb', components: { alpha: a.toFixed(3), blue: `0x${hex2(b)}`, green: `0x${hex2(g)}`, red: `0x${hex2(r)}` } };
}

function colorset(light, dark) {
    return (
        JSON.stringify(
            {
                colors: [
                    { color: colorsetColor(light), idiom: 'universal' },
                    { appearances: [{ appearance: 'luminosity', value: 'dark' }], color: colorsetColor(dark), idiom: 'universal' },
                ],
                info: { author: 'shared/app/build.mjs', version: 1 },
            },
            null,
            2,
        ) + '\n'
    );
}

/**
 * Every output of a platform as `Map<relative path, text>` from the two parsed sources and their hashes.
 * @param {'android'|'ios'} platform
 */
export function generate(platform, { entries, copyHash, tokens, tokensHash }) {
    const files = new Map();
    const problems = [];
    const shipped = entries.filter((entry) => entry.platforms.includes(platform));

    if (platform === 'android') {
        const lines = ['<?xml version="1.0" encoding="utf-8"?>', xmlHeader('shared/app/copy.fa.json', copyHash), '<resources>'];

        for (const { key, text } of shipped) {
            const value = shippedText(text);
            problems.push(...bidiProblems(key, value));
            const attributes = NOT_TRANSLATABLE.has(key) ? ' translatable="false"' : '';
            lines.push(`    <string name="${key}"${attributes}>${androidEscape(value)}</string>`);
        }

        const statements = `[{"include": "${ORIGIN}/.well-known/assetlinks.json"}]`;
        lines.push(`    <string name="asset_statements" translatable="false">${androidEscape(statements)}</string>`, '</resources>', '');
        files.set(OUTPUTS.android.strings, lines.join('\n'));

        for (const [file, pick] of [
            [OUTPUTS.android.colors, (color) => color.light],
            [OUTPUTS.android.nightColors, (color) => color.dark],
        ]) {
            const colors = ['<?xml version="1.0" encoding="utf-8"?>', xmlHeader('shared/app/tokens.json', tokensHash), '<resources>'];

            for (const color of tokens.colors) {
                colors.push(`    <color name="${color.name}">${androidColor(pick(color))}</color>`);
            }

            colors.push(`    <color name="night">${androidColor(tokens.night)}</color>`, '</resources>', '');
            files.set(file, colors.join('\n'));
        }
    } else {
        const header = stringsHeader('shared/app/copy.fa.json', copyHash);
        const line = (name, text) => {
            const value = shippedText(text, { string: '%@' });
            problems.push(...bidiProblems(name, value));

            return `"${name}" = "${stringsEscape(value)}";`;
        };
        const plistKeys = new Set(Object.values(INFO_PLIST_KEYS));

        files.set(OUTPUTS.ios.strings, [header, '', ...shipped.filter((entry) => !plistKeys.has(entry.key)).map((entry) => line(entry.key, entry.text)), ''].join('\n'));
        files.set(
            OUTPUTS.ios.infoPlist,
            [header, '', ...Object.entries(INFO_PLIST_KEYS).map(([plist, key]) => line(plist, shipped.find((entry) => entry.key === key).text)), ''].join('\n'),
        );
        files.set(
            OUTPUTS.ios.shareStrings,
            [header, '', ...SHARE_EXTENSION_KEYS.map((key) => line(key, shipped.find((entry) => entry.key === key).text)), ''].join('\n'),
        );

        const folder = OUTPUTS.ios.colors;
        files.set(`${folder}/Contents.json`, JSON.stringify({ info: { author: 'shared/app/build.mjs', version: 1 } }, null, 2) + '\n');

        for (const color of tokens.colors) {
            files.set(`${folder}/${pascalCase(color.name)}.colorset/Contents.json`, colorset(color.light, color.dark));
        }

        files.set(`${folder}/Night.colorset/Contents.json`, colorset(tokens.night, tokens.night));
        files.set(`${folder}/LaunchBackground.colorset/Contents.json`, colorset(tokens.night, tokens.night));
    }

    if (problems.length > 0) {
        throw new Error(`generated ${platform} copy:\n  ${problems.join('\n  ')}`);
    }

    return files;
}

/** Both sources, parsed and hashed (throws on any rule). */
export function loadSources({ copyFile = COPY_FILE, tokensFile = TOKENS_FILE } = {}) {
    const copyText = sourceText(copyFile);
    const tokensText = sourceText(tokensFile);

    return {
        entries: readCopy(JSON.parse(copyText)),
        copyHash: sha256(copyText),
        tokens: readTokens(JSON.parse(tokensText)),
        tokensHash: sha256(tokensText),
    };
}

/** Whether a platform adopted the generator under `root`: its main strings file carries the marker. */
export function adopted(platform, root = REPO) {
    const file = path.join(root, OUTPUTS[platform].strings);

    return existsSync(file) && readFileSync(file, 'utf8').includes(MARKER);
}

/** Colour sets under the iOS Colors folder that a generation no longer writes (written by this generator). */
function staleColorsets(root, files) {
    const folder = path.join(root, OUTPUTS.ios.colors);

    if (!existsSync(folder)) {
        return [];
    }

    return readdirSync(folder, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && entry.name.endsWith('.colorset'))
        .map((entry) => `${OUTPUTS.ios.colors}/${entry.name}`)
        .filter((dir) => !files.has(`${dir}/Contents.json`));
}

/** Writes the outputs of `platforms`; returns the written relative paths. */
export function write(platforms, sources, root = REPO) {
    const written = [];

    for (const platform of platforms) {
        const files = generate(platform, sources);

        for (const [relative, text] of files) {
            const file = path.join(root, relative);
            mkdirSync(path.dirname(file), { recursive: true });

            if (!existsSync(file) || readFileSync(file, 'utf8') !== text) {
                writeFileSync(file, text);
                written.push(relative);
            }
        }

        if (platform === 'ios') {
            for (const dir of staleColorsets(root, files)) {
                rmSync(path.join(root, dir), { recursive: true, force: true });
                written.push(`${dir} (removed)`);
            }
        }
    }

    return written;
}

/** Problems of the adopted platforms' outputs against a fresh generation (empty = current). */
export function check(sources, root = REPO) {
    const problems = [];

    for (const platform of PLATFORMS) {
        const files = generate(platform, sources);

        if (!adopted(platform, root)) {
            continue;
        }

        for (const [relative, text] of files) {
            const file = path.join(root, relative);

            if (!existsSync(file)) {
                problems.push(`${relative} is missing`);
            } else if (readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) {
                problems.push(`${relative} differs from a fresh generation`);
            }
        }

        if (platform === 'ios') {
            problems.push(...staleColorsets(root, files).map((dir) => `${dir} is no longer generated`));
        }
    }

    return problems;
}

function parseArgs(argv) {
    const args = { check: false, platforms: [], root: REPO, quiet: false };

    for (let index = 0; index < argv.length; index++) {
        const flag = argv[index];

        if (flag === '--check') {
            args.check = true;
        } else if (flag === '--quiet') {
            args.quiet = true;
        } else if (flag.startsWith('--platform=')) {
            args.platforms.push(...flag.slice('--platform='.length).split(','));
        } else if (flag === '--root') {
            args.root = path.resolve(argv[++index] ?? '');
        } else {
            throw new Error(`Unknown flag ${flag}`);
        }
    }

    const unknown = args.platforms.filter((platform) => !PLATFORMS.includes(platform));

    if (unknown.length > 0) {
        throw new Error(`Unknown platform ${unknown.join(', ')} (android, ios)`);
    }

    if (args.check && args.platforms.length > 0) {
        throw new Error('--check takes no --platform');
    }

    return args;
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const log = (line) => args.quiet || console.log(line);
    const sources = loadSources();
    const pending = PLATFORMS.filter((platform) => !adopted(platform, args.root) && !args.platforms.includes(platform));

    if (args.check) {
        const problems = check(sources, args.root);

        if (problems.length > 0) {
            console.error(`✗ ${problems.join('\n✗ ')}\n  node shared/app/build.mjs را اجرا کنید`);
            process.exitCode = 1;

            return;
        }

        log(`✓ copy.fa.json (${sources.entries.length} keys) and tokens.json (${sources.tokens.colors.length} colours) follow the rules; the outputs are current`);
    } else {
        const platforms = PLATFORMS.filter((platform) => args.platforms.includes(platform) || adopted(platform, args.root));
        const written = write(platforms, sources, args.root);
        log(written.length > 0 ? `✓ wrote ${written.join(', ')}` : `✓ the outputs of ${platforms.join(', ') || 'no platform'} are current`);
    }

    if (pending.length > 0) {
        log(`· not adopted yet (generated in memory only): ${pending.join(', ')}; adopt with --platform=<name>`);
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    try {
        main();
    } catch (error) {
        console.error(`✗ ${error instanceof Error ? error.message : error}`);
        process.exitCode = 1;
    }
}
